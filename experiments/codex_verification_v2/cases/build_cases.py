def oracle(family_id, facts):
    """A closed, deterministic rule interpreter, independent of advice and rendered prose."""
    if family_id == 'M01':
        if facts['accepted_at'] is None: return 'pause'
        threshold = facts['old_threshold'] if facts['accepted_at'] < facts['cutover'] else facts['new_threshold']
        return 'direct' if facts['amount'] < threshold else 'joint'
    if family_id == 'M02':
        if facts['delegated'] is None: return 'pause'
        allowed = set(facts['requested']) & set(facts['delegated'])
        return 'full' if allowed == set(facts['requested']) else ('limited' if allowed else 'reject')
    if family_id == 'M03':
        if facts['target_group'] is None: return 'pause'
        qualified = facts['gains'][facts['target_group']] >= facts['min_gain'] and facts['completion'] >= facts['min_completion']
        return ('full' if facts['studies'] >= 2 else 'pilot') if qualified else 'retain'
    if family_id == 'M04':
        if facts['exempt_blocks'] is None: return 'pause'
        rate = Fraction(100 * facts['present'], facts['planned'] - facts['block_size'] * facts['exempt_blocks'])
        return 'routine' if rate >= facts['routine_min'] else ('targeted' if rate >= facts['targeted_min'] else 'comprehensive')
    if family_id == 'R01':
        if facts['outage_end'] is None: return 'pause'
        minutes = (datetime.fromisoformat(facts['outage_end']) - datetime.fromisoformat(facts['outage_start'])).total_seconds() / 60
        return 'manual' if minutes >= facts['trigger_minutes'] else 'normal'
    if family_id == 'R02':
        if facts['second_valid'] is None: return 'pause'
        valid = 1 + int(facts['second_valid'])
        qualified = facts['consents'] == facts['participants'] and valid >= facts['minimum_escorts'] and facts['participants'] <= valid * facts['ratio_max']
        return 'depart' if qualified else 'postpone'
    if family_id == 'R03':
        if facts['class_code'] is None: return 'pause'
        if facts['class_code'] == 'E3' and facts['identity_verified'] and facts['escort_ready']: return 'escort'
        return 'deny'
    if family_id == 'R04':
        if facts['signed']['U3'] is None: return 'pause'
        good = all(facts['signed'][g] * facts['threshold_denominator'] >= n * facts['threshold_numerator']
                   for g,n in facts['eligible'].items())
        return 'release' if good else 'complete'
    raise ValueError(family_id)


def state_facts(f, state):
    facts = copy.deepcopy(f['facts'])
    val = f['changed_value'] if state == 'decisive_change' else (None if state == 'missing' else None)
    if state in ('decisive_change', 'missing'):
        if f['field'] == 'u3_signed': facts['signed']['U3'] = val
        else: facts[f['field']] = val
    # Redundant author bookkeeping must not contradict the single causal field.
    if f['id'] == 'R02': facts['valid_escorts'] = None if facts['second_valid'] is None else 1 + int(facts['second_valid'])
    return facts


def semantic_map(index, f):
    # Across 8 families each of base / changed / pause occupies each letter twice.
    return {f['base']: LETTERS[index%4], f['changed']: LETTERS[(index+1)%4],
            'pause': LETTERS[(index+2)%4], f['other']: LETTERS[(index+3)%4]}


